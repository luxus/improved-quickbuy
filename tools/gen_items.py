#!/usr/bin/env python3
"""Build src/items.gen.js from Valve's own game data (no third-party data):
  scripts/abilities.vdata        -> item id, shop icon (m_strShopIconLarge), slot type
  citadel_gc_mod_names_english   -> item id -> English display name (what the queue's ModName shows)
  m_vecComponentItems            -> the items an upgrade builds from
  m_iItemTier + generic_data.vdata m_nItemPricePerTier -> a component's full price (what an upgrade takes off)
Output: one packed string "normalizedname>folder/file;..." that the mod unpacks into a Map on first use."""
import re, sys

vdata, names, generic, out = sys.argv[1:5]
text = open(vdata, encoding='utf-8').read()
loc = open(names, encoding='utf-8', errors='replace').read()

tiers = [int(x) for x in re.search(r'm_nItemPricePerTier =\s*\[([^\]]*)\]', open(generic, encoding='utf-8').read()).group(1).replace(',', ' ').split()]
display = dict(re.findall(r'^\s*"(upgrade_[a-z0-9_]+|item_[a-z0-9_]+)"\s+"([^"]+)"', loc, re.M))

def norm(s):
    return re.sub(r'[^a-z0-9]', '', s.lower())

entries = {}
parts = {}
comp_ids = set()
blocks = re.findall(r'^\t([A-Za-z0-9_]+) =\s*\n\t\{(.*?)^\t\}', text, re.S | re.M)
for block_id, body in blocks:
    comp = re.search(r'm_vecComponentItems =\s*\n\s*\[(.*?)\]', body, re.S)
    if not comp or block_id not in display:
        continue
    ids = [c for c in re.findall(r'"([a-z0-9_]+)"', comp.group(1)) if c in display]
    comp_ids.update(ids)
    names = [norm(display[c]) for c in ids]
    if names:
        parts[norm(display[block_id])] = names
for block_id, body in re.findall(r'^\t([A-Za-z0-9_]+) =\s*\n\t\{(.*?)^\t\}', text, re.S | re.M):
    icon = re.search(r'm_strShopIconLarge = panorama:"file://\{images\}/items/([a-z0-9_]+)/([A-Za-z0-9_]+)\.psd"', body)
    if not icon or block_id not in display:
        continue
    if re.search(r'm_bDisabled = true', body):
        continue
    key = norm(display[block_id])
    if key and key not in entries:
        entries[key] = icon.group(1) + '/' + icon.group(2)

bodies = dict(blocks)
values = {}
for c in sorted(comp_ids):
    tier = re.search(r'm_iItemTier = "EModTier_(\d+)"', bodies.get(c, ''))
    if tier and int(tier.group(1)) < len(tiers):
        values[norm(display[c])] = tiers[int(tier.group(1))]
values_packed = ';'.join(f'{k}>{v}' for k, v in sorted(values.items()))
parts_packed = ';'.join(f'{k}>' + ','.join(v) for k, v in sorted(parts.items()))
packed = ';'.join(f'{k}>{v}' for k, v in sorted(entries.items()))
with open(out, 'w') as f:
    f.write('// generated by tools/gen_items.py from Valve game data (abilities.vdata, citadel_gc_mod_names_english, generic_data.vdata)\n')
    f.write(f'const IQB_ITEM_ICONS_PACKED = "{packed}";\n')
    f.write('// upgrade > the items it builds from (m_vecComponentItems): a queued component lowers the upgrade\'s price\n')
    f.write(f'const IQB_ITEM_PARTS_PACKED = "{parts_packed}";\n')
    f.write('// component > its full price (tier price): what buying an upgrade takes off for a component bought earlier\n')
    f.write(f'const IQB_ITEM_VALUES_PACKED = "{values_packed}";\n')
print(f'{len(entries)} items, {len(parts)} upgrades with components, {len(values)} component prices (tiers {tiers}) -> {out}', file=sys.stderr)
